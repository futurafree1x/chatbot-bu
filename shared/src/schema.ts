import { z } from 'zod';

/** IDs are kebab-case so content files stay predictable and URL-safe. */
export const Id = z
  .string()
  .regex(/^[a-z0-9]+(-[a-z0-9]+)*$/, 'IDs must be kebab-case, e.g. "ask-about-guitar"');

export const VariantSchema = z.object({
  text: z.string().min(1).max(500),
  weight: z.number().int().min(1).max(100),
  sourceId: Id.optional(),
});

export function totalWeight(variants: { weight: number }[]): number {
  let total = 0;
  for (const variant of variants) {
    total = total + variant.weight;
  }
  return total;
}

export const VariantListSchema = z
  .array(VariantSchema)
  .min(1)
  .refine((variants) => totalWeight(variants) === 100, {
    message: 'Variant weights must add up to 100',
  });

