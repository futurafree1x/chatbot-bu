import { z } from 'zod';

/** IDs are kebab-case so content files stay predictable and URL-safe. */
export const Id = z
  .string()
  .regex(/^[a-z0-9]+(-[a-z0-9]+)*$/, 'IDs must be kebab-case, e.g. "ask-about-guitar"');

export const VariantSchema = z.object({
  text: z.string().min(1).max(500),
  weight: z.number().int().min(1).max(100),
  sourceId: Id.optional(),
});

export function totalWeight(variants: { weight: number }[]): number {
  let total = 0;
  for (const variant of variants) {
    total = total + variant.weight;
  }
  return total;
}

export const VariantListSchema = z
  .array(VariantSchema)
  .min(1)
  .refine((variants) => totalWeight(variants) === 100, {
    message: 'Variant weights must add up to 100',
  });

//generated by Claude ^^

export const KeywordSchema = z
  .string()
  .regex(/^[a-z0-9]+$/, 'keywords must be single lowercase words e.g. guitar or gig')

// topic areas can be added in json dialogue file
export const TopicAreaSchema = z.object({   
  id: Id,
  label: z.string().min(1).max(40),
  tracked: z.boolean().default(true), // for small talk not counting towards exploration
});

// something the user might ask about -- the words that trigger it and possible replies
export const IntentSchema = z.object({ 
  id: Id,
  area: Id,
  keywords: z.array(KeywordSchema).min(1),
  variants: VariantListSchema,
});

/* CLAUDE GENERATED - " The whole conversation file: topic areas, 
's greeting and fallback, and every intent.  Also checks that every intent belongs 
to an area listed in `areas`. " */
export const DialogueSchema = z
  .object({
    areas: z.array(TopicAreaSchema).min(1),
    greeting: VariantListSchema,
    fallback: VariantListSchema,
    intents: z.array(IntentSchema).min(1),
  })
  .superRefine((dialogue, ctx) => {
    const areaIds = dialogue.areas.map((area) => area.id);

    dialogue.intents.forEach((intent, index) => {
      if (!areaIds.includes(intent.area)) {
        ctx.addIssue({
          code: 'custom',
          message: `Unknown area "${intent.area}". Add it to "areas" first.`,
          path: ['intents', index, 'area'],
        });
      }
    });
  });

export type Variant = z.infer<typeof VariantSchema>;
export type TopicArea = z.infer<typeof TopicAreaSchema>;
export type Intent = z.infer<typeof IntentSchema>;
export type Dialogue = z.infer<typeof DialogueSchema>;


